// Writes assets/landing/look-data.js: a few real exercises (name, instructions, doll scene) for the "איך זה נראה?" replica in landing.html.
// Run:  node scripts/make-landing-data.js
const fs = require('fs'), path = require('path');
global.window = {}; require('../shared/data.js');
const IDS = ['04-01', '02-01', '03-02', '06-01', '09-02'];
const all = [].concat(...window.HT_DATA.lessons.map(L => L.exercises.map(E => ({ L, E }))));
const pick = IDS.map(id => all.find(x => x.E.id === id)).filter(Boolean).map(({ L, E }) => ({ id: E.id, lesson: L.n, name: E.name, hold: E.hold, beats: E.beats, bpm: E.bpm, start: E.start, steps: E.steps, breath: E.breath, easier: E.easier, harder: E.harder, scene: E.scene }));
fs.writeFileSync(path.join(__dirname, '..', 'assets', 'landing', 'look-data.js'), '/* generated by scripts/make-landing-data.js */\nwindow.LOOK = ' + JSON.stringify(pick) + ';\n');
console.log(pick.map(p => p.id + ' ' + p.name).join('\n'));
