// Builds the single-page "room" app:   node build.js     (run from this folder)
//   ../shared/data.js   all lessons + exercises (texts, animation poses, muscles, calories)
//   ../index.html       the page shell; every screen is drawn by shared/app.js
// The older multi-page generator is kept as build-legacy.js (it writes ../lessons/ and overwrites ../index.html).
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const dataDir = path.join(__dirname, 'data');
const { DICT, MAP, SLIM } = require('./data/_muscles');
const lessons = fs.readdirSync(dataDir).filter(f => /^lesson\d+\.js$/.test(f)).sort().map(f => require(path.join(dataDir, f)));

const DEF = { sets: 3, reps: 10, hold: 0, sides: false, rest: 30, bpm: 80, beats: 4, music: 'steady', balance: false };
const LEVELS = { 'קל': 1, 'קל עד בינוני': 2, 'בינוני': 3, 'בינוני עד מתקדם': 4, 'מתקדם': 5 };
const ICON = { 'chair-basics': 'chair', 'chair-challenge': 'chair', 'broom-mobility': 'broom', 'broom-balance-strength': 'broom' };
const WEIGHT_KG = 65;                         // calories are an estimate for an average adult woman
const POINTS = 10;
const pad = n => String(n).padStart(2, '0');
const short = name => name.replace(/\s*\(.*?\)\s*/g, ' ').trim();

// Four muscle buttons per exercise: the first three on their own, the rest grouped as "supporting muscles".
function muscleButtons(m) {
  const list = m.p.map(k => ({ k, main: true })).concat(m.s.map(k => ({ k, main: false })));
  const one = o => ({ name: short(DICT[o.k][0]), full: DICT[o.k][0], desc: DICT[o.k][1] });
  if (list.length <= 4) return list.map(one);
  const rest = list.slice(3);
  return list.slice(0, 3).map(one).concat([{
    name: rest.every(o => !o.main) ? 'שרירים תומכים' : 'עוד שרירים', full: '',
    desc: '', items: rest.map(o => ({ name: DICT[o.k][0], desc: DICT[o.k][1] }))
  }]);
}

// Body areas that slim and tighten (up to three, primary muscles first, no repeats); none for stretching and mobility.
function slimAreas(m) {
  if (m.k) return [];
  return m.p.concat(m.s).map(k => SLIM[k]).filter((a, i, arr) => a && arr.indexOf(a) === i).slice(0, 3);
}

function prep(ex, L) {
  const e = Object.assign({}, DEF, ex), mus = MAP[e.slug];
  if (!mus) throw new Error('missing muscles for ' + e.slug);
  e.levelText = e.level || L.level;
  e.levelNum = LEVELS[e.levelText] || 3;
  const cycle = e.beats * 60 / e.bpm, work = e.hold ? e.hold : e.reps * cycle, per = e.sides ? 2 : 1;
  const active = e.sets * per * work;
  e.sec = Math.round(5 + active + (e.sides ? e.sets * 5 : 0) + (e.sets - 1) * e.rest);
  e.dose = e.hold ? `${e.sets} סטים × ${e.hold} שניות` : `${e.sets} סטים × ${e.reps} חזרות`;
  if (e.sides) e.dose += ' לכל צד';
  const met = mus.k === 'stretch' ? 2.3 : mus.k === 'mobility' ? 2.8 : 3.3 + 0.45 * (e.levelNum - 1) + (e.balance ? 0.3 : 0);
  e.kcal = Math.max(2, Math.round(met * WEIGHT_KG * (active + e.sets * 3) / 3600));
  e.mus = muscleButtons(mus);
  e.slim = slimAreas(mus);
  e.kind = mus.k || 'strength';
  return e;
}

const out = lessons.map(L => {
  const exercises = L.exercises.map((ex, i) => {
    const e = prep(ex, L);
    return {
      id: `${pad(L.n)}-${pad(i + 1)}`, i: i + 1, name: e.name, muscles: e.muscles, level: e.levelText, levelNum: e.levelNum, balance: e.balance,
      dose: e.dose, sec: e.sec, kcal: e.kcal, sets: e.sets, reps: e.reps, hold: e.hold, sides: e.sides, rest: e.rest, bpm: e.bpm, beats: e.beats, music: e.music,
      about: e.about, start: e.start, steps: e.steps, focus: e.focus, avoid: e.avoid, breath: e.breath, easier: e.easier, harder: e.harder,
      mus: e.mus, slim: e.slim, kind: e.kind, scene: e.scene
    };
  });
  const sec = exercises.reduce((a, e) => a + e.sec, 0) + exercises.length * 45;
  return { n: L.n, slug: L.slug, title: L.title, eqName: L.eqName, level: L.level, tag: L.tag, intro: L.intro, prep: L.prep, icon: ICON[L.slug] || 'logo', sec, exercises };
});

